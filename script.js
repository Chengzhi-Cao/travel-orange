function getTravelProfile(raw, mapPoints) {
  const distances = mapPoints.map((point) => getDistanceKm(raw.center, point));
  const maxDistance = Math.max(...distances, 0);
  const remotePoints = mapPoints.filter((point, index) => isRemotePoint(point, distances[index]));
  const spotCount = mapPoints.length;
  let days = 2;

  if (majorCityIds.has(raw.id)) {
    days = 3;
  }

  if (compactCityIds.has(raw.id)) {
    days = 2;
  }

  if (spotCount >= 4 && !compactCityIds.has(raw.id)) {
    days = Math.max(days, 3);
  }

  if (remotePoints.length >= 1 || maxDistance > 35) {
    days = Math.max(days, 3);
  }

  if (remotePoints.length >= 2 || maxDistance > 90) {
    days = Math.max(days, 4);
  }

  days = Math.min(days, 4);

  const pace =
    days === 2
      ? "景点集中，适合周末快走"
      : days === 3
        ? "城市核心加一段近郊"
        : "城市核心加两段远郊/自然线";

  return {
    days,
    distances,
    maxDistance,
    pace,
    remotePoints,
  };
}

function pickPoint(points, fallbackIndex = 0) {
  return points[fallbackIndex] || points[0];
}

function getUniquePoints(points) {
  const seen = new Set();
  return points.filter((point) => {
    if (!point || seen.has(point.name)) {
      return false;
    }

    seen.add(point.name);
    return true;
  });
}

function getUnusedPoint(points, usedNames) {
  return points.find((point) => point && !usedNames.has(point.name));
}

function markUsed(usedNames, points) {
  points.forEach((point) => {
    if (point) {
      usedNames.add(point.name);
    }
  });
}

function joinRouteNames(points, fallback) {
  const names = getUniquePoints(points).map((point) => point.name);
  return names.length > 0 ? names.join(" - ") : fallback;
}

function anchorIncludesPoint(anchor, point) {
  return Boolean(point && anchor && (anchor.includes(point.name) || point.name.includes(anchor)));
}

